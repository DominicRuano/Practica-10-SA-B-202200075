import logging
from dataclasses import dataclass

import psycopg
from psycopg.errors import UniqueViolation
from psycopg.rows import dict_row


logger = logging.getLogger(__name__)

# El bloqueo evita que dos replicas ejecuten el DDL y las semillas a la vez.
_MIGRATION_LOCK_ID = 2_022_000_755


@dataclass(frozen=True)
class CategoriaRegistro:
    id: int
    nombre: str
    descripcion: str


class RepositorioCategoriasPostgres:
    def __init__(self, database_url: str) -> None:
        if not database_url.strip():
            raise ValueError("DATABASE_URL no puede estar vacío.")
        self.database_url = database_url

    def _conectar(self) -> psycopg.Connection:
        return psycopg.connect(
            self.database_url,
            row_factory=dict_row,
            connect_timeout=5,
        )

    def inicializar(self) -> None:
        """Aplica el esquema y las semillas una sola vez de forma concurrente."""
        with self._conectar() as conexion:
            with conexion.transaction():
                conexion.execute(
                    "SELECT pg_advisory_xact_lock(%s)",
                    (_MIGRATION_LOCK_ID,),
                )
                conexion.execute(
                    """
                    CREATE TABLE IF NOT EXISTS categorias (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        nombre VARCHAR(80) NOT NULL,
                        descripcion VARCHAR(250) NOT NULL DEFAULT ''
                    )
                    """
                )
                conexion.execute(
                    """
                    CREATE UNIQUE INDEX IF NOT EXISTS uq_categorias_nombre
                    ON categorias (lower(trim(nombre)))
                    """
                )
                with conexion.cursor() as cursor:
                    cursor.executemany(
                        """
                        INSERT INTO categorias (nombre, descripcion)
                        VALUES (%s, %s)
                        ON CONFLICT DO NOTHING
                        """,
                        [
                            (
                                "Infraestructura",
                                "Aulas, mobiliario y espacios físicos.",
                            ),
                            (
                                "Soporte técnico",
                                "Equipo, plataformas y servicios tecnológicos.",
                            ),
                            (
                                "Servicios estudiantiles",
                                "Trámites y atención para estudiantes.",
                            ),
                        ],
                    )
        logger.info("Esquema y semillas de catálogo verificados")

    def disponible(self) -> bool:
        try:
            with psycopg.connect(
                self.database_url,
                connect_timeout=2,
            ) as conexion:
                conexion.execute("SELECT 1")
            return True
        except psycopg.Error:
            logger.warning("PostgreSQL no está disponible", exc_info=True)
            return False

    def listar(self) -> list[CategoriaRegistro]:
        with self._conectar() as conexion:
            filas = conexion.execute(
                """
                SELECT id, nombre, descripcion
                FROM categorias
                ORDER BY id
                """
            ).fetchall()
        return [self._convertir(fila) for fila in filas]

    def obtener(self, categoria_id: int) -> CategoriaRegistro | None:
        with self._conectar() as conexion:
            fila = conexion.execute(
                """
                SELECT id, nombre, descripcion
                FROM categorias
                WHERE id = %s
                """,
                (categoria_id,),
            ).fetchone()
        return self._convertir(fila) if fila else None

    def crear(self, nombre: str, descripcion: str) -> CategoriaRegistro:
        try:
            with self._conectar() as conexion:
                fila = conexion.execute(
                    """
                    INSERT INTO categorias (nombre, descripcion)
                    VALUES (%s, %s)
                    RETURNING id, nombre, descripcion
                    """,
                    (nombre, descripcion),
                ).fetchone()
        except UniqueViolation as error:
            raise NombreCategoriaDuplicado from error

        if fila is None:
            raise RuntimeError("No se pudo recuperar la categoría creada.")
        return self._convertir(fila)

    def actualizar(
        self, categoria_id: int, nombre: str, descripcion: str
    ) -> CategoriaRegistro | None:
        try:
            with self._conectar() as conexion:
                fila = conexion.execute(
                    """
                    UPDATE categorias
                    SET nombre = %s, descripcion = %s
                    WHERE id = %s
                    RETURNING id, nombre, descripcion
                    """,
                    (nombre, descripcion, categoria_id),
                ).fetchone()
        except UniqueViolation as error:
            raise NombreCategoriaDuplicado from error
        return self._convertir(fila) if fila else None

    def eliminar(self, categoria_id: int) -> bool:
        with self._conectar() as conexion:
            cursor = conexion.execute(
                "DELETE FROM categorias WHERE id = %s",
                (categoria_id,),
            )
        return cursor.rowcount > 0

    @staticmethod
    def _convertir(fila: dict[str, object]) -> CategoriaRegistro:
        return CategoriaRegistro(
            id=int(fila["id"]),
            nombre=str(fila["nombre"]),
            descripcion=str(fila["descripcion"]),
        )


class NombreCategoriaDuplicado(Exception):
    pass
